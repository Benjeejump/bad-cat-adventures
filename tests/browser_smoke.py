"""Integration checks. Run against python3 -m http.server 8000.
Requires Python Playwright and a Chromium executable, not application dependencies.
"""
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright

URL = os.environ.get('GAME_URL', 'http://127.0.0.1:8000/')

def check(condition, message):
    assert condition, message
    print('PASS', message)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':1366,'height':1024}, permissions=[], reduced_motion='reduce')
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(URL, wait_until='domcontentloaded')
    page.locator('#launch-silent').click(); page.locator('#test-drive').evaluate('(el)=>el.click()')
    page.wait_for_function('typeof badCatDiagnostics === "function"')
    check(page.title().startswith('Bad Cat Adventures'), 'Desktop app loads')
    page.wait_for_function('badCatDiagnostics().mapReady')
    check('OpenStreetMap' in page.locator('.leaflet-control-attribution').inner_text(), 'Bundled Leaflet and attribution initialise')
    check(page.evaluate('badCatDiagnostics().audioState')=='not-started', 'Audio waits for user gesture')
    page.wait_for_timeout(1200)
    before = page.evaluate('badCatDiagnostics()')
    page.wait_for_timeout(1200)
    after = page.evaluate('badCatDiagnostics()')
    check(after['distanceMetres'] > before['distanceMetres'], 'Test Drive car moves')
    cat = page.locator('#actor-badcat').get_attribute('style')
    page.wait_for_timeout(800)
    check(cat != page.locator('#actor-badcat').get_attribute('style'), 'Bad Cat chases the car')
    metro = page.locator('#actor-metro').get_attribute('style')
    page.wait_for_timeout(800)
    check(metro != page.locator('#actor-metro').get_attribute('style'), 'Metro chases the car')
    page.locator('.journey-settings summary').click()
    page.locator('#pause').click()
    before = page.evaluate('badCatDiagnostics().simulationElapsed')
    page.wait_for_timeout(600)
    check(page.evaluate('badCatDiagnostics().simulationElapsed') == before, 'Pause freezes Test Drive')
    page.locator('#pause').click()
    page.locator('#speed').select_option('4')
    before = page.evaluate('badCatDiagnostics().simulationElapsed')
    page.wait_for_timeout(800)
    check(page.evaluate('badCatDiagnostics().simulationElapsed') > before + 1.5, 'Speed control changes simulation speed')
    for vehicle in ['plane','submarine','car']:
        page.locator(f'.transform-picker [data-vehicle="{vehicle}"]').click()
        check(page.evaluate('badCatDiagnostics().vehicle')==vehicle, f'{vehicle} transformation works')
    page.locator('#sound').click()
    check(page.evaluate('badCatDiagnostics().audioState')=='running', 'Web Audio runs after interaction')
    page.locator('[data-gadget="shield"]').click()
    page.locator('#actor-metro').click()
    check('shielded' in page.locator('#map-stage').get_attribute('class'), 'Forcefield visible')
    for gadget in ['laser','sonar','bubble','puppy']:
        page.locator(f'[data-gadget="{gadget}"]').click()
        page.locator('#actor-metro').click()
        check(page.locator('.free-shot, .target-pop').count()>0, f'{gadget} visible targeted shot effect')
    for kind in ["vacuum","trap"]:
        page.evaluate("(kind)=>badCatAdventure.encounter(kind)",kind)
        check(page.locator('#encounter-dialog').evaluate('(el)=>el.open'), 'Encounter opens')
        page.locator('#encounter-actions button').first.click()
        if page.evaluate('badCatTargeting.raidActive()'):
            check(page.locator('.kitten-target').count()==20, 'Kitten decision starts its interactive scene')
            page.evaluate('badCatTargeting.tick(46)')
        else:
            check(page.locator('.story-world.resolved').count()==1, 'Decision starts an animated result scene')
        page.locator('#close-encounter').evaluate('(n)=>n.click()')
        check(not page.locator('#encounter-dialog').evaluate('(el)=>el.open'), 'Encounter resolves without game over')
    check(page.locator('.building-actor').count()==0, 'Fictional building clutter removed from map')
    check(page.locator('#actor-badcat img').get_attribute('src').endswith('bad-cat.png'), 'Bad Cat has an original BC face')
    check(page.locator('#actor-metro img').get_attribute('src').endswith('metro.png'), 'Metro has an original M face')
    page.locator('[data-view="hq"]').click()
    page.locator('#invention-name').fill('Dylan’s Waffle Ray <test>')
    page.locator('#invention-form button[type=submit]').click()
    check('Dylan’s Waffle Ray <test>' in page.locator('.use-invention').inner_text() and page.locator('.use-invention test').count()==0, 'Invention stored and rendered as safe text')
    page.locator('.use-invention').click();page.locator('[data-view="hq"]').click()
    page.locator('[data-equipment="Waffle wings"]').click()
    page.locator('[data-puppy="Luna"]').click()
    check('Luna' in page.locator('#puppy-status').inner_text(), 'Puppy interaction works')
    for _ in range(3): page.locator('#squid-target').click()
    check('You did it!' in page.locator('#squid-status').inner_text(), 'Squid challenge completes')
    mission = page.locator('#mission-text').inner_text()
    page.locator('#mission').click()
    check(page.locator('#mission-text').inner_text()!=mission, 'Surprise mission changes')
    page.reload(wait_until='domcontentloaded')
    page.locator('#launch-silent').click(); page.locator('#test-drive').evaluate('(el)=>el.click()')
    page.locator('[data-view="hq"]').click()
    check(page.locator('.use-invention').count()==1, 'Invention survives reload')
    check('Waffle wings' in page.locator('#garage-status').inner_text(), 'Garage equipment survives reload')
    page.evaluate('navigator.serviceWorker.ready')
    page.wait_for_function('navigator.serviceWorker.controller !== null')
    cached = page.evaluate('caches.keys()')
    check('bad-cat-shell-v13' in cached, 'Offline shell cached')
    context.set_offline(True)
    page.reload(wait_until='domcontentloaded')
    page.locator('#launch-silent').click(); page.locator('#test-drive').evaluate('(el)=>el.click()')
    page.locator('[data-view="hq"]').click()
    check(page.locator('.use-invention').count()==1, 'Offline reload restores app and progress')
    page.locator('#mission').click()
    page.locator('#squid-target').click()
    check('1 of 3' in page.locator('#squid-status').inner_text(), 'Offline HQ challenge remains playable')
    context.set_offline(False)
    for width,height in [(1280,800),(1024,600),(800,1280),(390,844)]:
        page.set_viewport_size({'width':width,'height':height})
        for view in ['drive','hq']:
            page.locator(f'[data-view="{view}"]').click()
            check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'{width}×{height} {view} has no horizontal overflow')
    page.set_viewport_size({'width':1280,'height':800})
    page.locator('[data-view="drive"]').click()
    page.screenshot(path='/tmp/bad-cat-tablet.png', full_page=True)
    # Browser-level permission denial, then synthetic allowed GPS fix.
    page.on('dialog', lambda d: d.accept())
    page.locator('.journey-settings summary').click()
    page.locator('#gps').click()
    page.wait_for_function('document.querySelector("#story").textContent.includes("permission")')
    check(page.evaluate('badCatDiagnostics().mode')=='unavailable', 'Denied GPS waits for an explicit mode choice')
    context.grant_permissions(['geolocation'])
    context.set_geolocation({'latitude':51.501,'longitude':-.142,'accuracy':12})
    page.locator('#gps').click()
    page.wait_for_function('badCatDiagnostics().mode === "gps"')
    check('±12 m' in page.locator('#accuracy').inner_text(), 'GPS fix and accuracy display')
    page.locator('#test-drive').click()
    check(page.evaluate('badCatDiagnostics().mode')=='test', 'Can stop GPS and return to simulation')
    stored = page.evaluate('localStorage.getItem("bad-cat-progress-v1")')
    check('latitude' not in stored and 'longitude' not in stored and '51.501' not in stored, 'Saved progress contains no location data')
    check(not errors, f'No uncaught JavaScript errors: {errors}')
    print('MAP RESULT',json.dumps(page.evaluate('badCatDiagnostics()')))
    browser.close()
